#!/usr/bin/env node
/*
 * Task 12: merge source/intake/wsNN.json into source/intake.json and generate
 * source/WORKSHEETS-INTAKE.md (per-paper summary, owner issues, second-read
 * counts, and a duplicate check by transcript text — not bytes).
 *
 * Duplicate check: each transcript is reduced to its set of normalised,
 * non-trivial lines (fidelity.normalise; blanks, page markers, footers and
 * header boilerplate dropped). For every pair we report the share of the
 * smaller paper's lines that also appear in the other paper.
 *
 * Deterministic: no dates. Usage: node scripts/merge-intake.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { normalise } = require('./fidelity.js');

const ROOT = path.resolve(__dirname, '..');
const INTAKE_DIR = path.join(ROOT, 'source', 'intake');
const TRANSCRIPTS = path.join(ROOT, 'source', 'transcripts');
const SAMPLES = path.join(ROOT, 'source', 'samples');

const ids = fs.readdirSync(INTAKE_DIR).filter(f => /^ws\d{2}\.json$/.test(f)).sort().map(f => f.slice(0, 4));
const papers = ids.map(id => JSON.parse(fs.readFileSync(path.join(INTAKE_DIR, `${id}.json`), 'utf8')));

const errors = [];
const sha = f => crypto.createHash('sha256').update(fs.readFileSync(f)).digest('hex');
const sum = (xs, f) => xs.reduce((a, x) => a + (f(x) || 0), 0);

for (const p of papers) {
  const pdf = path.join(SAMPLES, p.sourceFile);
  if (!fs.existsSync(pdf)) errors.push(`${p.ws}: source PDF missing: ${p.sourceFile}`);
  else if (sha(pdf) !== p.sha256) errors.push(`${p.ws}: sha256 differs from the PDF`);
  const sec = sum(p.sections, s => s.marks);
  const blk = sum(p.sections, s => sum(s.blocks, b => b.marks));
  if (sec !== p.printedTotal) errors.push(`${p.ws}: section marks ${sec} ≠ printed total ${p.printedTotal}`);
  if (blk !== p.printedTotal) errors.push(`${p.ws}: block marks ${blk} ≠ printed total ${p.printedTotal}`);
  if (!Array.isArray(p.pagesViewed) || p.pagesViewed.length !== p.pdfPages) errors.push(`${p.ws}: pagesViewed ${p.pagesViewed} vs ${p.pdfPages} pages`);
}

// ---- duplicate check by text ----
function lineSet(id) {
  const txt = fs.readFileSync(path.join(TRANSCRIPTS, `${id}.txt`), 'utf8');
  const out = new Set();
  for (const raw of txt.split('\n')) {
    if (/^=== page|^\[(चिह्न|चित्र|तालिका|\/तालिका)/.test(raw.trim())) continue;
    for (const col of raw.split(/\s{4,}|\t/)) {
      const n = normalise(col).replace(/____/g, '').replace(/\s+/g, ' ').trim();
      if (n.length < 8) continue;                                   // labels, blanks, marks
      if (/page|पृष्ठ|प्रष्ठ|अनुक्रमांक|विद्यार्थी का नाम|दिनांक|कक्षा/i.test(n)) continue; // footers + header boilerplate
      out.add(n);
    }
  }
  return out;
}
const sets = Object.fromEntries(ids.map(id => [id, lineSet(id)]));
const pairs = [];
for (let i = 0; i < ids.length; i++) for (let j = i + 1; j < ids.length; j++) {
  const a = sets[ids[i]], b = sets[ids[j]];
  let shared = 0; for (const l of a) if (b.has(l)) shared++;
  const pct = Math.round(1000 * shared / Math.min(a.size, b.size)) / 10;
  pairs.push({ a: ids[i], b: ids[j], shared, aLines: a.size, bLines: b.size, pctOfSmaller: pct });
}
pairs.sort((x, y) => y.pctOfSmaller - x.pctOfSmaller || x.a.localeCompare(y.a));

// ---- write intake.json ----
fs.writeFileSync(path.join(ROOT, 'source', 'intake.json'),
  JSON.stringify({ papers, duplicateCheck: pairs }, null, 2) + '\n');

// ---- write WORKSHEETS-INTAKE.md ----
const srLog = id => path.join(TRANSCRIPTS, 'second-read', `${id}.md`);
const L = [];
L.push('<!-- generated by scripts/merge-intake.js from source/intake/wsNN.json — do not edit -->');
L.push('# Worksheet intake (sprint v3)', '');
L.push('Every page of all 7 PDFs was viewed at 200 dpi, with 300+ dpi crops where needed. The text layer is garbled, so each paper was typed from the page images and then checked word by word by a second, independent reader (`source/transcripts/second-read/wsNN.md`).', '');
L.push('## Papers', '');
L.push('| ws | Source file | Printed title | Month | Total | Sections | Blocks | Items | Pictures (non-decorative) | ⚑ estimate | 2nd-read fixes |');
L.push('|---|---|---|---|---|---|---|---|---|---|---|');
for (const p of papers) {
  const blocks = sum(p.sections, s => s.blocks.length);
  const items = sum(p.sections, s => sum(s.blocks, b => b.items));
  const pics = p.sections.flatMap(s => s.blocks.flatMap(b => b.pictures || [])).filter(x => x.need !== 'decorative').length;
  L.push(`| ${p.ws} | \`${p.sourceFile}\` | ${p.printedTitle} | ${p.month || '—'} | ${p.printedTotal} | ${p.sections.length} | ${blocks} | ${items} | ${pics} | ${p.flagEstimate} | ${p.secondReadDisagreements} |`);
}
const tot = (f) => sum(papers, f);
L.push(`| **Total** | 7 papers | | | ${tot(p => p.printedTotal)} | | ${tot(p => sum(p.sections, s => s.blocks.length))} | ${tot(p => sum(p.sections, s => sum(s.blocks, b => b.items)))} | | ${tot(p => p.flagEstimate)} | ${tot(p => p.secondReadDisagreements)} |`, '');

L.push('## Mark arithmetic', '');
for (const p of papers) L.push(`- **${p.ws}:** ${p.markArithmetic}`);
L.push('');

L.push('## Duplicate check (by transcript text)', '');
L.push('Each value is the share of the smaller paper\'s distinct question/passage lines that also appear in the other paper. Only pairs above 10% are listed.', '');
L.push('| Pair | Shared lines | % of smaller |', '|---|---|---|');
for (const x of pairs.filter(x => x.pctOfSmaller > 10)) L.push(`| ${x.a} – ${x.b} | ${x.shared} of ${Math.min(x.aLines, x.bLines)} | ${x.pctOfSmaller}% |`);
L.push('');

L.push('## Pictures', '');
for (const p of papers) for (const s of p.sections) for (const b of s.blocks) for (const pic of (b.pictures || []))
  L.push(`- **${p.ws} ${b.label}** (p. ${pic.page}, ${pic.need}): ${pic.what}`);
L.push('');

L.push('## Likely paper-only blocks', '');
for (const p of papers) {
  const po = p.sections.flatMap(s => s.blocks.filter(b => b.paperOnlyLikely).map(b => `${b.label} (${b.pattern})`));
  L.push(`- **${p.ws}:** ${po.length ? po.join(', ') : 'none'}`);
}
L.push('');

L.push('## Issues for the owner (Gate 0), per paper', '');
for (const p of papers) {
  L.push(`### ${p.ws} · ${p.shortLabel || p.printedTitle}`, '');
  (p.issues || []).forEach((x, i) => L.push(`${i + 1}. ${x}`));
  L.push('');
}

L.push('## Hashes', '');
L.push('| ws | SHA-256 | Matches PDF |', '|---|---|---|');
for (const p of papers) L.push(`| ${p.ws} | \`${p.sha256}\` | ${errors.some(e => e.startsWith(p.ws + ': sha')) ? 'NO' : 'yes'} |`);
L.push('');
L.push('## Second-read logs', '');
for (const id of ids) L.push(`- ${id}: \`source/transcripts/second-read/${id}.md\`${fs.existsSync(srLog(id)) ? '' : ' (MISSING)'}`);
L.push('');

fs.writeFileSync(path.join(ROOT, 'source', 'WORKSHEETS-INTAKE.md'), L.join('\n'));

if (errors.length) { errors.forEach(e => console.error('ERROR: ' + e)); process.exit(1); }
console.log(`OK ${papers.length} papers merged; top overlap ${pairs[0].a}–${pairs[0].b} ${pairs[0].pctOfSmaller}%`);
